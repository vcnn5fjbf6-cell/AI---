CREATE TABLE IF NOT EXISTS procurement_after_sale (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  after_sale_no VARCHAR(64) NOT NULL COMMENT '售后单号',
  purchase_request_id BIGINT NOT NULL COMMENT '采购申请ID',
  purchase_request_item_id BIGINT NULL COMMENT '采购申请明细ID',
  quote_id BIGINT NOT NULL COMMENT '报价ID',
  quote_item_id BIGINT NOT NULL COMMENT '报价明细ID',
  supplier_id BIGINT NOT NULL COMMENT '供应商ID',
  requester_user_id BIGINT NOT NULL COMMENT '售后申请人',
  after_sale_type VARCHAR(32) NOT NULL COMMENT '售后类型 NO_REASON_RETURN/RETURN_EXCHANGE/REPLACE_ITEM/REPAIR/OTHER',
  reason VARCHAR(1000) NOT NULL COMMENT '售后原因',
  requested_qty DECIMAL(18,4) NOT NULL DEFAULT 1 COMMENT '售后数量',
  replacement_item_code VARCHAR(64) NULL COMMENT '更换商品编码',
  replacement_item_name VARCHAR(255) NULL COMMENT '更换商品名称',
  replacement_spec_model VARCHAR(255) NULL COMMENT '更换规格型号',
  replacement_unit VARCHAR(32) NULL COMMENT '更换单位',
  replacement_remark VARCHAR(1000) NULL COMMENT '更换说明',
  supplier_proposal_type VARCHAR(32) NULL COMMENT '供应商售后方案类型',
  supplier_proposal_remark VARCHAR(1000) NULL COMMENT '供应商售后方案说明',
  supplier_replacement_item_code VARCHAR(64) NULL COMMENT '供应商方案更换商品编码',
  supplier_replacement_item_name VARCHAR(255) NULL COMMENT '供应商方案更换商品名称',
  supplier_replacement_spec_model VARCHAR(255) NULL COMMENT '供应商方案更换规格型号',
  supplier_replacement_unit VARCHAR(32) NULL COMMENT '供应商方案更换单位',
  supplier_replacement_unit_price DECIMAL(18,2) NULL COMMENT '供应商方案更换单价',
  supplier_replacement_line_amount DECIMAL(18,2) NULL COMMENT '供应商方案更换金额',
  supplier_proposed_at DATETIME NULL COMMENT '供应商给出方案时间',
  requester_confirm_user_id BIGINT NULL COMMENT '需求方方案确认人',
  requester_confirmed_at DATETIME NULL COMMENT '需求方方案确认时间',
  requester_confirm_remark VARCHAR(1000) NULL COMMENT '需求方方案确认意见',
  status VARCHAR(32) NOT NULL DEFAULT 'PENDING' COMMENT '状态 PENDING待供应商方案/PROPOSAL_PENDING方案待确认/APPROVED已通过/REJECTED已驳回',
  approver_user_id BIGINT NULL COMMENT '审核人',
  approved_at DATETIME NULL COMMENT '审核时间',
  approval_remark VARCHAR(1000) NULL COMMENT '审核意见',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by BIGINT NULL,
  updated_by BIGINT NULL,
  is_deleted TINYINT NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 0,
  UNIQUE KEY uk_after_sale_no (after_sale_no),
  KEY idx_after_sale_quote_item (quote_item_id, status, is_deleted),
  KEY idx_after_sale_requester (requester_user_id, status, is_deleted),
  KEY idx_after_sale_supplier (supplier_id, status, is_deleted),
  KEY idx_after_sale_status (status, created_at, is_deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='采购订单售后申请';
