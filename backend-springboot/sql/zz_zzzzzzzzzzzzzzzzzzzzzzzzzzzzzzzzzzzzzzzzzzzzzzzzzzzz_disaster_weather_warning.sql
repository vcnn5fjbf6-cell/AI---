  push_group VARCHAR(128) NULL COMMENT '推送群组',
  important_event_group VARCHAR(128) NULL COMMENT '一级戒备重要事件群',
  room_manager VARCHAR(128) NULL COMMENT '机房经理',
  push_description TEXT NULL COMMENT '推送说明',
  pushed TINYINT NOT NULL DEFAULT 0 COMMENT '是否已推送 1是0否',
  guard_level3_accepted TINYINT NOT NULL DEFAULT 0 COMMENT '三级戒备是否接单',
  guard_level2_accepted TINYINT NOT NULL DEFAULT 0 COMMENT '二级戒备是否接单',
  guard_level1_accepted TINYINT NOT NULL DEFAULT 0 COMMENT '一级戒备是否接单',
  city_code VARCHAR(64) NOT NULL COMMENT '城市code',
  created_person VARCHAR(128) NULL COMMENT '创建人',
  weather_raw_json LONGTEXT NULL COMMENT '天气信息接口数据',
  today_weather_json LONGTEXT NULL COMMENT '今日天气接口数据',
  today_weather_info TEXT NULL COMMENT '今日天气信息',
  warning_raw_json LONGTEXT NULL COMMENT '预警信息接口数据',
  warning_info TEXT NULL COMMENT '预警信息',
  warning_type_extract TEXT NULL COMMENT '预警类型提取',
  guard_tag VARCHAR(128) NULL COMMENT '重保标签',
  guard_alert_tag VARCHAR(128) NULL COMMENT '重保戒备标签',
  wet_bulb_advice TEXT NULL COMMENT '湿球温度输出建议',
  guard_steps TEXT NULL COMMENT '重保步骤',
  relative_humidity DECIMAL(10,2) NULL COMMENT '相对湿度',
  saturation_temp DECIMAL(10,2) NULL COMMENT '饱和/露点温度计算',
  dry_bulb_temp DECIMAL(10,2) NULL COMMENT '干球温度',
  wet_bulb_temp DECIMAL(10,2) NULL COMMENT '湿球温度',
  wet_bulb_info TEXT NULL COMMENT '湿球温度信息提取',
  tomorrow_weather TEXT NULL COMMENT '明日天气',
  day2_weather TEXT NULL COMMENT '后2天',
  day3_weather TEXT NULL COMMENT '后3天',
  day4_weather TEXT NULL COMMENT '后4天',
  day5_weather TEXT NULL COMMENT '后5天',
  day6_weather TEXT NULL COMMENT '后6天',
  day7_weather TEXT NULL COMMENT '后7天',
  day8_weather TEXT NULL COMMENT '后8天',
  day9_weather TEXT NULL COMMENT '后9天',
  day10_weather TEXT NULL COMMENT '后10天',
  day11_weather TEXT NULL COMMENT '后11天',
  day12_weather TEXT NULL COMMENT '后12天',
  day13_weather TEXT NULL COMMENT '后13天',
  day14_weather TEXT NULL COMMENT '后14天',
  real_time_precipitation DECIMAL(10,2) NULL COMMENT '实时降雨量',
  manual_trigger TINYINT NOT NULL DEFAULT 0 COMMENT '手动触发',
  send_status VARCHAR(32) NOT NULL DEFAULT 'NOT_SENT' COMMENT '发送状态 NOT_SENT/SENT/FAILED/SKIPPED',
  message_id VARCHAR(128) NULL COMMENT '飞书消息ID',
  last_error TEXT NULL COMMENT '最后错误',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建人ID',
  updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '更新人ID',
  is_deleted TINYINT NOT NULL DEFAULT 0 COMMENT '删除标记 0未删 1已删',
  version INT NOT NULL DEFAULT 0 COMMENT '版本号',
  UNIQUE KEY uk_disaster_weather_query_record_id (query_record_id),
  KEY idx_disaster_weather_created_at (created_at),
  KEY idx_disaster_weather_type_status (record_type, send_status),
  KEY idx_disaster_weather_city (city_code),
  KEY idx_disaster_weather_deleted (is_deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='灾害预警天气记录';

