CREATE TABLE IF NOT EXISTS disaster_weather_record (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
  query_record_id VARCHAR(64) NOT NULL COMMENT '查询记录ID',
  record_type VARCHAR(32) NOT NULL DEFAULT 'DAILY' COMMENT '记录类型 DAILY/WEEKLY/WARNING',
  push_city VARCHAR(128) NOT NULL COMMENT '推送城市',
