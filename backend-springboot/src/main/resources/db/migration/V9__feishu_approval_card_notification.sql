CREATE TABLE IF NOT EXISTS feishu_approval_card_notification (
  id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
  approval_task_id BIGINT NOT NULL COMMENT '审批任务ID',
  purchase_request_id BIGINT NOT NULL COMMENT '采购申请ID',
  approver_user_id BIGINT NOT NULL COMMENT '审批人用户ID',
  submit_round INT NOT NULL DEFAULT 1 COMMENT '提交轮次',
  receive_id_type VARCHAR(32) NOT NULL DEFAULT 'open_id' COMMENT '飞书接收ID类型',
  receive_id VARCHAR(128) NULL COMMENT '飞书接收ID',
  message_id VARCHAR(128) NULL COMMENT '飞书消息ID',
  card_token VARCHAR(128) NOT NULL COMMENT '卡片一次性校验令牌',
  status VARCHAR(32) NOT NULL DEFAULT 'PENDING' COMMENT '状态 PENDING/SENT/FAILED/APPROVED/RETURNED/CLOSED',
  action VARCHAR(32) NULL COMMENT '审批动作',
  retry_count INT NOT NULL DEFAULT 0 COMMENT '重试次数',
  last_error VARCHAR(1000) NULL COMMENT '最后错误',
  sent_at DATETIME NULL COMMENT '发送时间',
  acted_at DATETIME NULL COMMENT '处理时间',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  created_by BIGINT NOT NULL DEFAULT 0 COMMENT '创建人',
  updated_by BIGINT NOT NULL DEFAULT 0 COMMENT '更新人',
  is_deleted TINYINT NOT NULL DEFAULT 0 COMMENT '删除标记',
  version INT NOT NULL DEFAULT 0 COMMENT '版本号',
  UNIQUE KEY uk_feishu_approval_card_task (approval_task_id),
  UNIQUE KEY uk_feishu_approval_card_token (card_token),
  KEY idx_feishu_approval_card_user_status (approver_user_id, status),
  KEY idx_feishu_approval_card_request (purchase_request_id),
  KEY idx_feishu_approval_card_message (message_id),
  KEY idx_feishu_approval_card_deleted (is_deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='飞书审批卡片通知';
